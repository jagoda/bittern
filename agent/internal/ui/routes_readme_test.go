package ui

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"testing"
)

// updateRouteReadme regenerates the route table in ui/README.md. The -update
// flag follows the golden-file convention used by the render and status tests.
var updateRouteReadme = flag.Bool("update", false, "regenerate the route table in ui/README.md")

const (
	routeReadmeFile   = "../../../ui/README.md"
	routeTableBegin   = "<!-- BEGIN uiRoutes table: generated by agent/internal/ui/routes_readme_test.go; do not edit -->"
	routeTableEnd     = "<!-- END uiRoutes table -->"
	routeTableCommand = "cd agent && go test ./internal/ui -run TestUIRouteTableREADME -update"
)

// TestUIRouteTableREADME fails when the route table in ui/README.md is not the
// table uiRoutes renders, so the documentation cannot drift from the inventory.
func TestUIRouteTableREADME(t *testing.T) {
	data, err := os.ReadFile(routeReadmeFile)
	if err != nil {
		t.Fatalf("read ui/README.md: %v", err)
	}
	readme := string(data)
	start := strings.Index(readme, routeTableBegin)
	end := strings.Index(readme, routeTableEnd)
	if start < 0 || end < 0 || end < start {
		t.Fatalf("ui/README.md does not contain the route table markers:\n%s\n%s",
			routeTableBegin, routeTableEnd)
	}
	end += len(routeTableEnd)
	current := readme[start:end]
	expected := renderRouteTable()
	if current == expected {
		return
	}
	if *updateRouteReadme {
		updated := readme[:start] + expected + readme[end:]
		if err := os.WriteFile(routeReadmeFile, []byte(updated), 0o644); err != nil {
			t.Fatalf("write ui/README.md: %v", err)
		}
		return
	}
	t.Fatalf("the route table in ui/README.md has drifted from uiRoutes\nrun `%s` to regenerate it\n\nREADME:\n%s\n\nuiRoutes:\n%s",
		routeTableCommand, current, expected)
}

func renderRouteTable() string {
	var table strings.Builder
	table.WriteString(routeTableBegin)
	table.WriteString("\n\n")
	table.WriteString("| Method | Path | Template | Auth | BIT-020 |\n")
	table.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, route := range uiRoutes {
		method := route.Method
		if method == "" {
			method = "*"
		}
		template := "-"
		if route.Template != "" {
			template = "`" + route.Template + "`"
		}
		fmt.Fprintf(&table, "| %s | `%s` | %s | %s | %s |\n",
			method, route.Pattern, template, routeYesNo(route.Auth), routeYesNo(route.Responsive))
	}
	table.WriteString("\n")
	table.WriteString(routeTableEnd)
	return table.String()
}

func routeYesNo(value bool) string {
	if value {
		return "Yes"
	}
	return "No"
}
