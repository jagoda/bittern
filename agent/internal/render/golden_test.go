// repoRoot walks up from the package directory until it finds the agent module,
// then returns the repository root above it.
func repoRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return filepath.Dir(dir)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("could not find go.mod above the test directory")
		}
		dir = parent
	}
}

func TestGolden(t *testing.T) {
	for _, testCase := range goldenCases {
		t.Run(testCase.name, func(t *testing.T) {
			configPath := filepath.Join(repoRoot(t), testCase.configPath)
			expectedDir := filepath.Join(repoRoot(t), testCase.expectedDir)
			outputDir := t.TempDir()

			files, validationErrors, err := Generate(configPath, outputDir)
			if err != nil {
				t.Fatalf("generate: %v", err)
			}

			if len(testCase.wantErrors) > 0 {
				if len(files) != 0 {
					t.Fatalf("invalid configuration produced %d files", len(files))
				}
				got := make([]string, 0, len(validationErrors))
				for _, item := range validationErrors {
					got = append(got, item.Path+" "+item.Rule)
				}
				sort.Strings(got)
				if strings.Join(got, "\n") != strings.Join(testCase.wantErrors, "\n") {
					t.Fatalf("want errors %v, got %v", testCase.wantErrors, got)
				}
				entries, err := os.ReadDir(outputDir)
				if err != nil {
					t.Fatal(err)
				}
				if len(entries) != 0 {
					t.Fatalf("invalid configuration wrote %d files", len(entries))
				}
				if *update {
					if err := os.RemoveAll(expectedDir); err != nil {
						t.Fatal(err)
					}
				}
				return
			}

			if len(validationErrors) != 0 {
				t.Fatalf("expected valid configuration, got %v", validationErrors)
			}
			for _, file := range files {
				wantHeader := fmt.Sprintf("# Generated by Bittern from appliance.yaml; do not edit.\n# appliance.yaml schema version: %d\n", config.SchemaVersion)
				if !bytes.HasPrefix(file.Data, []byte(wantHeader)) {
					t.Errorf("%s does not start with the do-not-edit header", file.Path)
				}
			}

			if *update {
				if err := os.RemoveAll(expectedDir); err != nil {
					t.Fatal(err)
				}
				if err := WriteTree(expectedDir, files); err != nil {
					t.Fatal(err)
				}
			}

			differences, err := diffTrees(expectedDir, outputDir)
			if err != nil {
				t.Fatal(err)
			}
			if len(differences) != 0 {
				t.Fatalf("golden drift (run go test ./internal/render -update to regenerate):\n  %s",
					strings.Join(differences, "\n  "))
			}

			// A second independent load and render must be byte-identical.
			secondDir := t.TempDir()
			if _, validationErrors, err := Generate(configPath, secondDir); err != nil || len(validationErrors) != 0 {
				t.Fatalf("second generate: errors=%v err=%v", validationErrors, err)
			}
			differences, err = diffTrees(outputDir, secondDir)
			if err != nil {
				t.Fatal(err)
			}
			if len(differences) != 0 {
				t.Fatalf("renderer is not byte-identical across runs:\n  %s", strings.Join(differences, "\n  "))
			}
		})
	}
}

// TestDiffDetectsOneCharacterDrift proves the golden comparison is exact.
func TestDiffDetectsOneCharacterDrift(t *testing.T) {
	expected := t.TempDir()
	actual := t.TempDir()
	const relative = "chrony/chrony.conf"
	for _, dir := range []string{expected, actual} {
		if err := os.MkdirAll(filepath.Join(dir, "chrony"), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	original := []byte("# generated\npool pool.ntp.org iburst\n")
	if err := os.WriteFile(filepath.Join(expected, filepath.FromSlash(relative)), original, 0o644); err != nil {
		t.Fatal(err)
	}
	mutated := bytes.Replace(original, []byte("pool"), []byte("pooL"), 1)
	if err := os.WriteFile(filepath.Join(actual, filepath.FromSlash(relative)), mutated, 0o644); err != nil {
		t.Fatal(err)
	}

	differences, err := diffTrees(expected, actual)
	if err != nil {
		t.Fatal(err)
	}
	if len(differences) != 1 || !strings.Contains(differences[0], relative) {
		t.Fatalf("one-character drift was not detected: %v", differences)
	}
}

func diffTrees(expectedDir, actualDir string) ([]string, error) {
	expected, err := readTree(expectedDir)
	if err != nil {
		return nil, err
	}
	actual, err := readTree(actualDir)
	if err != nil {
		return nil, err
	}

	names := make([]string, 0, len(expected)+len(actual))
	seen := make(map[string]bool, len(expected)+len(actual))
	for name := range expected {
		if !seen[name] {
			names = append(names, name)
			seen[name] = true
		}
	}
	for name := range actual {
		if !seen[name] {
			names = append(names, name)
			seen[name] = true
		}
	}
	sort.Strings(names)

	var differences []string
	for _, name := range names {
		want, wantOK := expected[name]
		got, gotOK := actual[name]
		switch {
		case !wantOK:
			differences = append(differences, name+": unexpected file")
		case !gotOK:
			differences = append(differences, name+": missing file")
		case !bytes.Equal(want, got):
			differences = append(differences, name+": content differs")
		}
	}
	return differences, nil
}

func readTree(root string) (map[string][]byte, error) {
	files := make(map[string][]byte)
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, os.ErrNotExist) {
				return nil
			}
			return err
		}
		if entry.IsDir() {
			return nil
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[filepath.ToSlash(relative)] = data
		return nil
	})
	if errors.Is(err, os.ErrNotExist) {
		return files, nil
	}
	return files, err
}
