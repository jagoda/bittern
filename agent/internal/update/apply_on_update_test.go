func changePoolStart(t *testing.T, env *testEnv, value string) {
	t.Helper()
	data, err := os.ReadFile(env.configPath)
	if err != nil {
		t.Fatal(err)
	}
	changed := bytes.Replace(data, []byte("pool_start: 10.77.0.50"), []byte("pool_start: "+value), 1)
	if bytes.Equal(changed, data) {
		t.Fatal("the pool start did not change")
	}
	if err := os.WriteFile(env.configPath, changed, 0o644); err != nil {
		t.Fatal(err)
	}
}

