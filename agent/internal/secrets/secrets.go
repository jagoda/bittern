// Package secrets reads and writes /etc/bittern/secrets.yaml.
//
// The file holds generated values: the Frigate administrator password, the TLS
// private key, and the one-time setup token. It is mode 0600. Callers that log
// or render a document must use the shared redactor and never print a value.
package secrets

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

// SetupTokenFilename is the operator convenience copy of the one-time setup
// token. It lives under the state root and is removed when setup completes.
const SetupTokenFilename = "setup-token"

// Document is the secrets.yaml structure. Unknown fields are not preserved on
// rewrite; the file is entirely generated by Bittern.
//
// The short code is stored only as a hash and an expiry. The plaintext exists
// in the operator's console block for the short lifetime and is never written
// here.
type Document struct {
	SchemaVersion         int      `yaml:"schema_version"`
	Identity              Identity `yaml:"identity"`
	AdminPassword         string   `yaml:"admin_password,omitempty"`
	SetupToken            string   `yaml:"setup_token,omitempty"`
	SetupShortCodeHash    string   `yaml:"setup_short_code_hash,omitempty"`
	SetupShortCodeExpires string   `yaml:"setup_short_code_expires_at,omitempty"`
	TLS                   TLS      `yaml:"tls"`
}

// Identity ties the generated secrets to the appliance identity record.
type Identity struct {
	ID string `yaml:"id"`
}

// TLS holds the PEM private key for the generated self-signed certificate.
type TLS struct {
	PrivateKeyPEM string `yaml:"private_key_pem"`
}

// Load reads and parses a secrets document.
func Load(path string) (Document, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Document{}, err
	}
	var document Document
	if err := yaml.Unmarshal(data, &document); err != nil {
		return Document{}, fmt.Errorf("parse secrets %s: %w", path, err)
	}
	return document, nil
}

// Values returns every generated secret for registration with a redactor.
func (d Document) Values() []string {
	return []string{d.AdminPassword, d.SetupToken, d.TLS.PrivateKeyPEM}
}

// Save writes the document atomically with mode 0600.
func Save(path string, document Document) error {
	data, err := yaml.Marshal(document)
	if err != nil {
		return err
	}
	return WriteFileAtomic(path, data, 0o600)
}

// SetupTokenPath returns the mode 0600 operator copy of the setup token.
func SetupTokenPath(stateRoot string) string {
	return filepath.Join(stateRoot, SetupTokenFilename)
}

// RemoveSetupTokenFile removes the operator convenience copy. A missing file
// is not an error because setup may already have consumed it.
func RemoveSetupTokenFile(path string) error {
	if path == "" {
		return errors.New("secrets: empty setup token path")
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// ClearSetupToken removes the one-time setup token and the short-code hash
// after the administrator password has been stored. It is safe to call when
// they are already gone.
func ClearSetupToken(path string) error {
	if path == "" {
		return errors.New("secrets: empty path")
	}
	document, err := Load(path)
	if err != nil {
		return err
	}
	if document.SetupToken == "" && document.SetupShortCodeHash == "" &&
		document.SetupShortCodeExpires == "" {
		return nil
	}
	document.SetupToken = ""
	document.SetupShortCodeHash = ""
	document.SetupShortCodeExpires = ""
	return Save(path, document)
}

// WriteFileAtomic replaces path through a temporary file in the same
// directory, fsyncs it, and renames it into place.
func WriteFileAtomic(path string, data []byte, mode os.FileMode) error {
	directory := filepath.Dir(path)
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return err
	}
	temp, err := os.CreateTemp(directory, ".tmp-"+filepath.Base(path)+"-*")
	if err != nil {
		return err
	}
	tempName := temp.Name()
	cleanup := func() {
		_ = temp.Close()
		_ = os.Remove(tempName)
	}
	if err := temp.Chmod(mode); err != nil {
		cleanup()
		return err
	}
	if _, err := temp.Write(data); err != nil {
		cleanup()
		return err
	}
	if err := temp.Sync(); err != nil {
		cleanup()
		return err
	}
	if err := temp.Close(); err != nil {
		_ = os.Remove(tempName)
		return err
	}
	if err := os.Rename(tempName, path); err != nil {
		_ = os.Remove(tempName)
		return err
	}
	return nil
}
