"""Tests for packaging/cleanup.sh against a temporary root.

The test uses only the Python standard library. Fake systemctl, findmnt, nft,
docker, and docker-compose commands in a temporary PATH let the script exercise
its file removal and Clean-state check without touching the development host.
"""

