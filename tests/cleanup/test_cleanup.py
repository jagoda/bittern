class CleanupTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name) / "root"
        self.fakebin = Path(self.temp.name) / "bin"
        self.root.mkdir()
        self.fakebin.mkdir()
        self.write_fake("findmnt", FAKE_FINDMNT)
        self.write_fake("systemctl", FAKE_SYSTEMCTL)
        self.write_fake("nft", FAKE_NFT)
        self.write_fake("apt-get", FAKE_APT)
        self.write_fake("docker", FAKE_DOCKER)
        self.write_fake("docker-compose", FAKE_DOCKER_COMPOSE)
        self.populate()

    def tearDown(self) -> None:
        self.temp.cleanup()

    def write_fake(self, name: str, body: str) -> None:
        path = self.fakebin / name
        path.write_text(body, encoding="utf-8")
        path.chmod(0o755)

    def path(self, relative: str) -> Path:
        return self.root / relative.lstrip("/")

    def write(self, relative: str, content: str, mode: int = 0o644) -> Path:
        path = self.path(relative)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        path.chmod(mode)
        return path

    def populate(self) -> None:
        for unit in (
            "bittern-first-boot.service",
            "bittern-image-prewarm.service",
            "bitternd.service",
            "bittern-frigate.service",
        ):
            self.write(f"/etc/systemd/system/{unit}", "[Service]\nExecStart=/bin/true\n")
        self.write(
            "/etc/systemd/system/bittern-frigate.service.d/10-local.conf",
            "[Service]\nEnvironment=LOCAL=1\n",
        )
        wants = self.path("/etc/systemd/system/multi-user.target.wants")
        wants.mkdir(parents=True, exist_ok=True)
        (wants / "bitternd.service").symlink_to("../bitternd.service")
        self.write("/etc/systemd/system/nftables.service", "[Service]\nExecStart=/bin/true\n")
        self.write("/usr/bin/bittern", "binary\n", 0o755)
        self.write("/usr/bin/bitternd", "binary\n", 0o755)

        self.write("/etc/bittern/appliance.yaml", "schema_version: 2\n")
        self.write("/etc/bittern/secrets.yaml", f"setup_token: {SECRET}\n", 0o600)
        self.write("/etc/bittern/tls/server.crt", "certificate\n")

        self.write("/var/lib/bittern/first-boot.json", "{}\n")
        self.write("/var/lib/bittern/identity.json", "{}\n")
        self.write("/var/lib/bittern/current", "1\n")
        self.write("/var/lib/bittern/journal.json", "{}\n")
        self.write("/var/lib/bittern/setup-token", f"{SECRET}\n", 0o600)
        self.write("/var/lib/bittern/generations/1/manifest.json", "{}\n")
        self.write("/var/lib/bittern/compose/compose.yaml", "name: bittern-frigate\n")
        self.write("/var/lib/bittern/compose/compose.override.yaml", "services: {}\n")
        self.write("/var/lib/bittern/frigate/config.yml", HEADER + "mqtt:\n  enabled: false\n")
        self.write("/var/lib/bittern/media/recording.mp4", "recording-bytes\n")
        self.write("/var/lib/bittern/media/frigate.db", "database-bytes\n")

        for name in ("10-lan0.link", "10-cam0.link", "10-lan0.network"):
            self.write(f"/etc/systemd/network/{name}", HEADER + "[Match]\nName=lan0\n")
        self.write("/etc/systemd/network/10-cam0.network", "[Match]\nName=cam0\n")
        self.write("/etc/systemd/network/20-unmanaged.network", "[Match]\nName=eth9\n")
        self.write("/etc/systemd/network/30-bittern-extra.network", HEADER + "[Match]\nName=x\n")

        self.write(
            "/etc/dnsmasq.d/bittern.conf",
            HEADER + "dhcp-host=aa:bb:cc:dd:ee:ff,10.77.0.20\n",
        )
        self.write(
            "/etc/dnsmasq.d/bittern-reservation.conf",
            HEADER + "dhcp-host=aa:bb:cc:dd:ee:50,10.77.0.50\n",
        )
        self.write("/etc/dnsmasq.d/other.conf", "# not Bittern\n")
        self.write("/etc/dnsmasq.conf.bittern-poc.bak", "# stock dnsmasq conffile\n")
        self.write(
            "/etc/dnsmasq.conf",
            "# stock dnsmasq conffile\n"
            "# Added by Bittern packaging/install.sh: load drop-ins when Debian does not.\n"
            "conf-dir=/etc/dnsmasq.d/,*.conf\n",
        )
        self.write("/etc/chrony/chrony.conf", HEADER + "pool pool.ntp.org iburst\n")
        self.write("/etc/nftables.conf", HEADER + "table inet bittern {}\n")

        self.write(
            "/etc/docker/daemon.json",
            '{"iptables": false, "ip-forward": false, "bridge": "none"}\n',
        )

        fake = self.path("/fake")
        fake.mkdir()
        (fake / "nft-bittern").write_text("table\n", encoding="utf-8")
        (fake / "frigate-container").write_text("container\n", encoding="utf-8")
        (fake / "frigate-image").write_text("image\n", encoding="utf-8")

    def run_cleanup(
        self,
        *args: str,
        input_text: str | None = None,
        mounts: list[Path] | None = None,
        env_extra: dict[str, str] | None = None,
    ) -> subprocess.CompletedProcess[str]:
        env = os.environ.copy()
        env["PATH"] = f"{self.fakebin}:{env['PATH']}"
        env["BITTERN_FAKE_ROOT"] = str(self.root)
        env["BITTERN_CLEANUP_FAKE_APT"] = "1"
        env["FAKE_MOUNTS"] = "\n".join(str(path) for path in (mounts or []))
        env.update(env_extra or {})
        return subprocess.run(
            [str(SCRIPT), "--root", str(self.root), *args],
            input=input_text,
            text=True,
            capture_output=True,
            env=env,
            check=False,
        )

    def snapshot(self) -> dict[str, str]:
        result = {}
        for path in sorted(self.root.rglob("*")):
            relative = path.relative_to(self.root).as_posix()
            if relative == "fake-command.log":
                continue
            if path.is_symlink():
                result[relative] = "link:" + os.readlink(path)
            elif path.is_file():
                result[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
            else:
                result[relative] = "dir"
        return result

    def command_log(self) -> str:
        log = self.path("/fake-command.log")
        return log.read_text(encoding="utf-8") if log.exists() else ""

    def test_dry_run_plans_without_changing_anything(self) -> None:
        before = self.snapshot()
        result = self.run_cleanup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("mode: plan only", result.stdout)
        self.assertIn("stop and disable bitternd.service", result.stdout)
        self.assertIn("remove", result.stdout)
        self.assertIn("dry run complete", result.stdout)
        self.assertEqual(before, self.snapshot())
        self.assertNotIn(SECRET, result.stdout + result.stderr)

    def test_plan_recognises_the_bittern_reservation_as_owned(self) -> None:
        result = self.run_cleanup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(
            "remove Bittern dnsmasq file "
            + str(self.path("/etc/dnsmasq.d/bittern-reservation.conf")),
            result.stdout,
        )
        self.assertNotIn("ownership not established", result.stderr)

    def test_cleanup_removes_the_bittern_reservation_and_leaves_a_manual_one(self) -> None:
        manual = self.write(
            "/etc/dnsmasq.d/vendor-camera.conf",
            "dhcp-host=aa:bb:cc:dd:ee:99,10.77.0.99\n",
        )
        result = self.run_cleanup("--yes")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("ownership not established", result.stderr)
        self.assertIn(str(manual), result.stdout)
        self.assertTrue(manual.exists())
        self.assertFalse(self.path("/etc/dnsmasq.d/bittern-reservation.conf").exists())

    def test_plan_restores_chrony_and_nftables_stock_conffiles(self) -> None:
        result = self.run_cleanup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("preserve rendered", result.stdout)
        self.assertIn("restore the stock chrony conffile with apt-get", result.stdout)
        self.assertIn("restore the stock nftables conffile with apt-get", result.stdout)
        self.assertIn("restore stock", result.stdout)
        self.assertIn("dnsmasq.conf", result.stdout)

    def test_plan_restores_conffiles_before_network_and_dnsmasq_removal(self) -> None:
        result = self.run_cleanup("--purge-network")
        self.assertEqual(result.returncode, 0, result.stderr)
        output = result.stdout
        chrony = output.index("restore the stock chrony conffile with apt-get")
        nftables = output.index("restore the stock nftables conffile with apt-get")
        network = output.index("remove generated network file")
        dnsmasq = output.index("remove Bittern dnsmasq file")
        self.assertLess(chrony, network)
        self.assertLess(chrony, dnsmasq)
        self.assertLess(nftables, network)
        self.assertLess(nftables, dnsmasq)

    def test_default_cleanup_keeps_live_generated_network_files(self) -> None:
        result = self.run_cleanup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("keep live generated network files", result.stdout)
        self.assertIn("--purge-network", result.stdout)
        self.assertNotIn("remove generated network file", result.stdout)
        self.assertNotIn("remove known Bittern recovery file", result.stdout)

    def test_cleanup_keeps_media_and_second_run_is_noop(self) -> None:
        media = self.path("/var/lib/bittern/media")
        result = self.run_cleanup("--yes", mounts=[media])
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("clean state verified", result.stdout)
        self.assertNotIn(SECRET, result.stdout + result.stderr)
        self.assertFalse(self.path("/etc/bittern").exists())
        self.assertFalse(self.path("/etc/systemd/system/bitternd.service").exists())
        self.assertFalse(
            self.path("/etc/systemd/system/bittern-frigate.service.d").exists()
        )
        self.assertFalse(self.path("/var/lib/bittern/first-boot.json").exists())
        self.assertFalse(self.path("/var/lib/bittern/setup-token").exists())
        self.assertFalse(self.path("/var/lib/bittern/compose").exists())
        self.assertFalse(self.path("/usr/bin/bittern").exists())
        self.assertFalse(self.path("/usr/bin/bitternd").exists())
        self.assertEqual(
            self.path("/etc/chrony/chrony.conf").read_text(encoding="utf-8"),
            "# stock chrony conffile\n",
        )
        self.assertEqual(
            self.path("/etc/nftables.conf").read_text(encoding="utf-8"),
            "# stock nftables conffile\n",
        )
        self.assertFalse(self.path("/etc/dnsmasq.conf.bittern-poc.bak").exists())
        self.assertEqual(
            self.path("/etc/dnsmasq.conf").read_text(encoding="utf-8"),
            "# stock dnsmasq conffile\n",
        )
        self.assertEqual(
            self.path("/var/lib/bittern/media/recording.mp4").read_text(encoding="utf-8"),
            "recording-bytes\n",
        )
        self.assertEqual(
            self.path("/var/lib/bittern/media/frigate.db").read_text(encoding="utf-8"),
            "database-bytes\n",
        )
        # The live generated network files are kept by default because the
        # next install needs the DHCP-provided resolver for apt. The install
        # and first boot replace them.
        self.assertTrue(self.path("/etc/systemd/network/10-lan0.link").exists())
        self.assertTrue(self.path("/etc/systemd/network/10-cam0.network").exists())
        self.assertTrue(self.path("/etc/systemd/network/30-bittern-extra.network").exists())
        self.assertTrue(self.path("/etc/systemd/network/20-unmanaged.network").exists())
        self.assertFalse(self.path("/etc/dnsmasq.d/bittern.conf").exists())
        self.assertFalse(self.path("/etc/dnsmasq.d/bittern-reservation.conf").exists())
        self.assertFalse(self.path("/etc/docker/daemon.json").exists())
        self.assertTrue(self.path("/var/backups/bittern").is_dir())
        backups = list(self.path("/var/backups/bittern").iterdir())
        self.assertEqual(len(backups), 1)
        self.assertEqual(
            backups[0].read_text(encoding="utf-8"),
            '{"iptables": false, "ip-forward": false, "bridge": "none"}\n',
        )
        self.assertFalse(self.path("/fake/nft-bittern").exists())
        self.assertFalse(self.path("/fake/frigate-container").exists())
        log = self.command_log()
        self.assertIn("systemctl disable --now bittern-frigate.service", log)
        self.assertIn("systemctl disable --now nftables.service", log)
        self.assertIn("docker-compose", log)
        self.assertIn("down", log)
        self.assertIn("apt-get", log)
        self.assertIn("chrony", log)
        self.assertIn("nftables", log)
        self.assertNotIn("docker image rm", log)
        self.assertTrue(self.path("/fake/frigate-image").exists())

        before = self.snapshot()
        log_size = len(log)
        second = self.run_cleanup("--yes", mounts=[media])
        self.assertEqual(second.returncode, 0, second.stdout + second.stderr)
        self.assertIn("already clean", second.stdout)
        self.assertEqual(before, self.snapshot())
        new_log = self.command_log()[log_size:]
        for mutation in (
            "disable",
            "daemon-reload",
            "delete table",
            "docker rm",
            "down",
            "image rm",
        ):
            self.assertNotIn(mutation, new_log)

    def test_purge_network_removes_generated_network_files(self) -> None:
        result = self.run_cleanup("--yes", "--purge-network")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("clean state verified", result.stdout)
        self.assertIn("generated network files", result.stdout)
        for name in ("10-lan0.link", "10-cam0.link", "10-lan0.network", "10-cam0.network", "30-bittern-extra.network"):
            self.assertFalse(self.path(f"/etc/systemd/network/{name}").exists(), name)
        self.assertTrue(self.path("/etc/systemd/network/20-unmanaged.network").exists())

    def test_purge_media_refuses_a_mount_and_keeps_contents(self) -> None:
        media = self.path("/var/lib/bittern/media")
        result = self.run_cleanup(
            "--yes",
            "--purge-media",
            input_text="DELETE MEDIA\n",
            mounts=[media],
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("unmount it first", result.stderr)
        self.assertEqual(
            self.path("/var/lib/bittern/media/recording.mp4").read_text(encoding="utf-8"),
            "recording-bytes\n",
        )

    def test_purge_media_requires_the_second_confirmation(self) -> None:
        result = self.run_cleanup("--yes", "--purge-media", input_text="wrong\n")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("media purge not confirmed", result.stderr)
        self.assertTrue(self.path("/var/lib/bittern/media/recording.mp4").exists())

    def test_purge_media_removes_an_unmounted_directory(self) -> None:
        result = self.run_cleanup(
            "--yes",
            "--purge-media",
            input_text="DELETE MEDIA\n",
        )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("clean state verified", result.stdout)
        self.assertFalse(self.path("/var/lib/bittern/media").exists())

    def test_conffile_restore_failure_fails_cleanup(self) -> None:
        result = self.run_cleanup(
            "--yes",
            env_extra={"FAKE_APT_FAIL": "chrony"},
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("could not restore the chrony conffile", result.stderr)
        restored = self.path("/etc/chrony/chrony.conf")
        self.assertTrue(restored.exists())
        self.assertTrue(restored.read_text(encoding="utf-8").startswith(HEADER))
        self.assertFalse(self.path("/var/backups/bittern/chrony-chrony.conf.rendered").exists())

    def test_failed_restore_keeps_rendered_conffile_and_dhcp_resolver(self) -> None:
        result = self.run_cleanup(
            "--yes",
            env_extra={"FAKE_APT_FAIL": "nftables"},
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("could not restore the nftables conffile", result.stderr)
        rendered = self.path("/etc/nftables.conf")
        self.assertTrue(rendered.exists())
        self.assertTrue(rendered.read_text(encoding="utf-8").startswith(HEADER))
        self.assertFalse(
            self.path("/var/backups/bittern/nftables-nftables.conf.rendered").exists()
        )
        # The network files carry the DHCP-supplied resolver. They must still be
        # present when the restore fails, or apt loses DNS and the appliance
        # loses its local resolver.
        self.assertTrue(self.path("/etc/systemd/network/10-lan0.network").exists())
        self.assertTrue(self.path("/etc/systemd/network/10-lan0.link").exists())
        self.assertTrue(self.path("/etc/dnsmasq.d/bittern.conf").exists())

    def test_unowned_daemon_config_is_reported_and_left(self) -> None:
        custom = self.write("/etc/docker/daemon.json", '{"live-restore": true}\n')
        result = self.run_cleanup("--yes")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("ownership not established", result.stderr)
        self.assertTrue(custom.exists())
        self.assertIn("/etc/docker/daemon.json", result.stdout)

    def test_purge_images_is_opt_in(self) -> None:
        result = self.run_cleanup("--yes", "--purge-images")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("docker image rm", self.command_log())
        self.assertFalse(self.path("/fake/frigate-image").exists())


if __name__ == "__main__":
    unittest.main()
